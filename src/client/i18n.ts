function normalizeLanguage(language?: string | null) {
  return language?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function detectLanguage() {
  if (typeof window === "undefined") return "en";
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY) ?? navigator.language);
}

function persistLanguage(language: string) {
  if (typeof document === "undefined") return;
  const normalized = normalizeLanguage(language);
  document.documentElement.lang = normalized;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
}

void i18n.use(initReactI18next).init({
  fallbackLng: "en",
  initAsync: false,
  interpolation: { escapeValue: false },
  lng: detectLanguage(),
  resources: {
    en: { translation: {} },
    "zh-CN": { translation: zhCN },
  },
  supportedLngs: ["en", "zh-CN"],
});

persistLanguage(i18n.resolvedLanguage ?? i18n.language);
i18n.off("languageChanged", persistLanguage);
i18n.on("languageChanged", persistLanguage);

export function localeFor(language?: string) {
  return normalizeLanguage(language) === "zh-CN" ? "zh-CN" : "en-US";
}

export default i18n;
